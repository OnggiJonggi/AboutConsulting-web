CREATE TABLE ANALYSIS_RESULT(
  ANALYSIS_RESULT_NO NUMBER PRIMARY KEY,
  CONSULTANT_STUDENT_NO REFERENCES CONSULTANT_STUDENT(CONSULTANT_STUDENT_NO),
