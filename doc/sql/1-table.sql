CREATE TABLE FILE_INFO(
  FILE_NO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ORIGINAL_NAME VARCHAR2(330) NOT NULL,
  CHANGED_NAME VARCHAR2(50) NOT NULL,
  MIME VARCHAR2(50) NOT NULL,
  FILE_SIZE NUMBER NOT NULL,
  SAVE_PATH VARCHAR2(50) NOT NULL
);
COMMENT ON TABLE FILE_INFO IS '파일';
COMMENT ON COLUMN FILE_INFO.FILE_NO IS '파일 식별번호';
COMMENT ON COLUMN FILE_INFO.ORIGINAL_NAME IS '원본 이름';
COMMENT ON COLUMN FILE_INFO.CHANGED_NAME IS '변경된 이름';
COMMENT ON COLUMN FILE_INFO.MIME IS 'MIME 타입';
COMMENT ON COLUMN FILE_INFO.FILE_SIZE IS '크기';
COMMENT ON COLUMN FILE_INFO.SAVE_PATH IS '저장 경로';


CREATE TABLE FILE_HISTORY(
  HISTORY_NO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FILE_NO NUMBER REFERENCES FILE_INFO(FILE_NO),
  ORIGINAL_NAME VARCHAR2(330) NOT NULL,
  CHANGED_NAME VARCHAR2(50) NOT NULL,
  SAVE_PATH VARCHAR2(50) NOT NULL,
  ACTION VARCHAR2(10) NOT NULL,
  ACTION_AT DATE DEFAULT SYSDATE, --JAVA 기준
  ACTION_BY NUMBER REFERENCES MEMBER(MEMBER_NO)
);
COMMENT ON TABLE FILE_HISTORY IS '파일 기록';
COMMENT ON COLUMN FILE_HISTORY.FILE_NO IS '파일 식별번호';
COMMENT ON COLUMN FILE_HISTORY.ORIGINAL_NAME IS '원본 이름';
COMMENT ON COLUMN FILE_HISTORY.CHANGED_NAME IS '변경된 이름';
COMMENT ON COLUMN FILE_HISTORY.SAVE_PATH IS '저장 경로';
COMMENT ON COLUMN FILE_HISTORY.ACTION IS '변경 상태';
COMMENT ON COLUMN FILE_HISTORY.ACTION_AT IS '변경 시각';
COMMENT ON COLUMN FILE_HISTORY.ACTION_BY IS '변경자';


CREATE TABLE RECORD_ANALYSIS_GROUP(
  GROUP_NO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  STUDENT_NO NUMBER REFERENCES STUDENT(STUDENT_NO) NOT NULL,
  STARTED_AT DATE DEFAULT SYSDATE,
  COMPLETED_AT DATE,
  STATUS VARCHAR2(10)
);
COMMENT ON TABLE RECORD_ANALYSIS_GROUP IS '생기부 분석결과 묶음';
COMMENT ON COLUMN RECORD_ANALYSIS_GROUP.GROUP_NO IS '묶음 식별번호';
COMMENT ON COLUMN RECORD_ANALYSIS_GROUP.STUDENT_NO IS '학생 식별번호';
COMMENT ON COLUMN RECORD_ANALYSIS_GROUP.STARTED_AT IS '시작 시각';
COMMENT ON COLUMN RECORD_ANALYSIS_GROUP.COMPLETED_AT IS '완료 시각';
COMMENT ON COLUMN RECORD_ANALYSIS_GROUP.STATUS IS '상태값';


CREATE TABLE ANALYSIS_ITEM(
  ITEM_NO NUMBER PRIMARY KEY,
  FIELD VARCHAR2(70) NOT NULL
);
COMMENT ON TABLE ANALYSIS_ITEM IS '분석결과 항목';
COMMENT ON COLUMN ANALYSIS_ITEM.ITEM_NO IS '항목 식별번호';
COMMENT ON COLUMN ANALYSIS_ITEM.FIELD IS '항목';

CREATE TABLE RECORD_ANALYSIS(
  GROUP_NO NUMBER REFERENCES RECORD_ANALYSIS_GROUP(GROUP_NO) NOT NULL,
  ITEM_NO NUMBER REFERENCES ANALYSIS_ITEM(ITEM_NO) NOT NULL,
  ANALYSIS CLOB NOT NULL,
  
  PRIMARY KEY (ITEM_NO, GROUP_NO)
);
COMMENT ON TABLE RECORD_ANALYSIS IS '생기부 분석결과';
COMMENT ON COLUMN RECORD_ANALYSIS.GROUP_NO IS '묶음 식별번호';
COMMENT ON COLUMN RECORD_ANALYSIS.ITEM_NO IS '항목 식별번호';
COMMENT ON COLUMN RECORD_ANALYSIS.ANALYSIS IS '분석 결과';


CREATE TABLE RECORD_FILE(
  GROUP_NO NUMBER REFERENCES RECORD_ANALYSIS_GROUP(GROUP_NO) NOT NULL,
  FILE_NO NUMBER REFERENCES FILE_INFO(FILE_NO) NOT NULL
);
COMMENT ON TABLE RECORD_FILE IS '생기부-파일';
COMMENT ON COLUMN RECORD_FILE.GROUP_NO IS '묶음 식별번호';
COMMENT ON COLUMN RECORD_FILE.FILE_NO IS '파일 식별번호';


