CREATE TABLE MEMBER(
  MEMBER_NO NUMBER PRIMARY KEY,
  ID VARCHAR2(300) NOT NULL,
  PWD VARCHAR2(300) NOT NULL,
  NAME VARCHAR2(300) NOT NULL,
  NICKNAME VARCHAR2(300) NOT NULL
);
COMMENT ON TABLE MEMBER IS '회원';
COMMENT ON COLUMN MEMBER.MEMBER_NO IS '아이디';
COMMENT ON COLUMN MEMBER.PWD IS '비밀번호';
COMMENT ON COLUMN MEMBER.NAME IS '이름';
COMMENT ON COLUMN MEMBER.NICKNAME IS '별명';


CREATE TABLE ROLE_INFO(
  ROLE_NO NUMBER PRIMARY KEY,
  NAME VARCHAR2(30) NOT NULL
);
COMMENT ON TABLE ROLE_INFO IS '권한';
COMMENT ON COLUMN ROLE_INFO.ROLE_NO IS '권한 식별번호';
COMMENT ON COLUMN ROLE_INFO.NAME IS '이름';


CREATE TABLE MEMBER_ROLE(
  MEMBER_NO NUMBER REFERENCES MEMBER(MEMBER_NO) NOT NULL,
  ROLE_NO NUMBER REFERENCES ROLE_INFO(ROLE_NO) NOT NULL
);
COMMENT ON TABLE MEMBER_ROLE IS '회원-권한';
COMMENT ON COLUMN MEMBER_ROLE.MEMBER_NO IS '회원 식별번호';
COMMENT ON COLUMN MEMBER_ROLE.ROLE_NO IS '권한 식별번호';


CREATE TABLE URL_RESOURCE(
  RESOURCE_NO NUMBER PRIMARY KEY,
  PATTERN VARCHAR2(50) NOT NULL,
  HTTP_METHOD VARCHAR2(10) NOT NULL
);
COMMENT ON TABLE URL_RESOURCE IS 'URL자원';
COMMENT ON COLUMN URL_RESOURCE.RESOURCE_NO IS 'URL 식별번호';
COMMENT ON COLUMN URL_RESOURCE.PATTERN IS 'URL패턴';
COMMENT ON COLUMN URL_RESOURCE.HTTP_METHOD IS 'HTTP 메서드';


CREATE TABLE ROLE_URL(
  ROLE_NO NUMBER REFERENCES ROLE_INFO(ROLE_NO) NOT NULL,
  RESOURCE_NO NUMBER REFERENCES URL_RESOURCE(RESOURCE_NO) NOT NULL
);
COMMENT ON TABLE ROLE_URL IS '권한-URL';
COMMENT ON COLUMN ROLE_URL.ROLE_NO IS '권한 식별번호';
COMMENT ON COLUMN ROLE_URL.RESOURCE_NO IS '자원 식별번호';


CREATE TABLE CONSULTANT(
  CONSULTANT_NO NUMBER PRIMARY KEY,
  MEMBER_NO NUMBER REFERENCES MEMBER(MEMBER_NO) NOT NULL
);
COMMENT ON TABLE CONSULTANT IS '컨설턴트';
COMMENT ON COLUMN CONSULTANT.CONSULTANT_NO IS '컨설턴트 식별번호';
COMMENT ON COLUMN CONSULTANT.MEMBER_NO IS '회원 식별번호';


CREATE TABLE SCHOOL(
  SCHOOL_CODE NUMBER PRIMARY KEY,
  NAME VARCHAR2(100) NOT NULL,
  SIDO VARCHAR2(70) NOT NULL,
  SIGUNGU VARCHAR2(70),
  COEDUCATION VARCHAR2(10),
  SPECIALIZED VARCHAR2(33),
  SPECIALIZED_TYPE VARCHAR2(70)
);
COMMENT ON TABLE SCHOOL IS '고등학교';
COMMENT ON COLUMN SCHOOL.SCHOOL_CODE IS '학교 행정표준코드';
COMMENT ON COLUMN SCHOOL.NAME IS '이름';
COMMENT ON COLUMN SCHOOL.SIDO IS '시/도';
COMMENT ON COLUMN SCHOOL.SIGUNGU IS '시/군/구';
COMMENT ON COLUMN SCHOOL.COEDUCATION IS '남여공학';
COMMENT ON COLUMN SCHOOL.SPECIALIZED IS '전문고';
COMMENT ON COLUMN SCHOOL.SPECIALIZED_TYPE IS '전문고 종류';


CREATE TABLE STUDENT(
  STUDENT_NO NUMBER PRIMARY KEY,
  SCHOOL_CODE NUMBER REFERENCES SCHOOL(SCHOOL_CODE) NOT NULL,
  NAME VARCHAR2(33) NOT NULL,
  GRADE NUMBER NOT NULL,
  SEMESTER NUMBER NOT NULL,
  TRACK VARCHAR2(330)
);
COMMENT ON TABLE STUDENT IS '학생';
COMMENT ON COLUMN STUDENT.STUDENT_NO IS '학생 식별번호';
COMMENT ON COLUMN STUDENT.SCHOOL_CODE IS '학교 행정표준코드';
COMMENT ON COLUMN STUDENT.NAME IS '이름';
COMMENT ON COLUMN STUDENT.GRADE IS '학년';
COMMENT ON COLUMN STUDENT.SEMESTER IS '학기';
COMMENT ON COLUMN STUDENT.TRACK IS '트랙';


CREATE TABLE TARGET_INFO(
